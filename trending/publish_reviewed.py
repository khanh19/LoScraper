"""Manually import individually reviewed evidence into an isolated preview only.

This is not routine social publication or a claim that judge calibration passed.
Review labels are supplied by an operator, never generated by the extraction LLM.
"""
import argparse,json,os
import psycopg
from datetime import datetime,timezone,timedelta
from pathlib import Path

from .__main__ import load_env_files
from .engine import local_store
from .engine_store import EngineStore,digest
from .model import parse_time
from .multimodal import candidate_from_evidence


def import_reviewed(ledger,feed,review,now):
    at=parse_time(review.get('reviewed_at'))
    if not review.get('reviewer') or not at or not now-timedelta(days=7)<=at<=now:
        raise ValueError('human_review_receipt_required')
    entries=review.get('records',[])
    if not isinstance(entries,list) or len(entries)>90:raise ValueError('review_record_limit')
    results=[]
    for entry in entries:
        result={'evidence_id':entry.get('evidence_id'),'published':False}
        try:
            row=ledger.db.execute('SELECT * FROM discovery_engine_evidence WHERE id=%s',(entry['evidence_id'],)).fetchone()
            if not row or entry.get('approved') is not True or entry.get('claims_sha256')!=digest(row['extraction']):
                raise ValueError('review_does_not_match_claims')
            if row['reasons'] or (row['judgment'] or {}).get('verdict')!='accept':raise ValueError('held_evidence')
            package=row['record'];package['fetched_at']=row['fetched_at']
            if row['fetched_at']<now-timedelta(hours=72) or not package.get('verification_known'):
                raise ValueError('unverified_source')
            account=feed.db.execute('SELECT * FROM discovery_publisher_accounts WHERE platform=%s AND owner_key=%s AND NOT revoked',
                (package['platform'],package['owner_key'])).fetchone()
            if not account or not account['publication_enabled']:raise ValueError('publication_gated')
            venues=feed.db.execute('SELECT * FROM discovery_verified_venues WHERE publisher_id=%s AND city_slug=%s AND NOT revoked',
                (account['publisher_id'],row['city_hint'])).fetchall()
            candidates=[candidate_from_evidence(package,row['extraction'],account,v,now)[0] for v in venues]
            candidates=[c for c in candidates if c]
            if len(candidates)!=1:raise ValueError('unresolved_destination_or_facts')
            with feed.db.transaction():
                feed.register(package['platform'],package['platform'].title(),True,package['platform'])
                item_id=feed.upsert(candidates[0],now)
                audit_id=EngineStore(feed).evidence(package,row['extraction'],row['judgment'])
                feed.db.execute('UPDATE discovery_engine_evidence SET discovery_item_id=%s WHERE id=%s',(item_id,audit_id))
                evaluated=feed.db.execute('SELECT reason FROM discovery_evaluate_all(%s,%s) WHERE item_id=%s',
                    (now,row['city_hint'],item_id)).fetchone()
                result.update(item_id=item_id,published=bool(evaluated and evaluated['reason']=='eligible'),
                              reason=evaluated['reason'] if evaluated else 'withheld')
        except (ValueError,KeyError,TypeError) as exc:
            result['reason']=str(exc) if isinstance(exc,ValueError) else type(exc).__name__
        except psycopg.Error:
            result["reason"]="database_write_failed_no_replay"
        results.append(result)
    return results


def main():
    p=argparse.ArgumentParser(description=__doc__);p.add_argument('--env-file',action='append',default=[])
    p.add_argument('--review',type=Path,required=True);args=p.parse_args();load_env_files(args.env_file)
    from urllib.parse import urlsplit
    if not urlsplit(os.environ.get('DATABASE_URL','')).path.startswith('/lo_setup_check_'):p.error('isolated preview required')
    feed=local_store(os.environ.get('DATABASE_URL'));ledger=local_store(os.environ.get('OPENAI_DATABASE_URL'))
    try:
        results=import_reviewed(ledger,feed,json.loads(args.review.read_text()),datetime.now(timezone.utc))
        print(json.dumps({'results':results,'routine_social_publication':False},ensure_ascii=False))
        return 2 if any(not r['published'] for r in results) else 0
    finally:feed.close();ledger.close()


if __name__=='__main__':raise SystemExit(main())
